#!/usr/bin/env python3
"""Build js/icons.js from the SVGs exported from Figma (assets/icons/figma/*.svg).

The SVG files are the source of truth and are never edited. This script only:
  * replaces the paint color OUTSIDE <mask>/<defs> with currentColor, so CSS `color` can recolor an icon
    (masks, gradients and geometry are kept exactly as exported);
  * drops the outer fill-opacity / stroke-opacity, because opacity now comes from the CSS color;
  * optionally crops the viewBox of wrapper exports (back, close-circle) so the glyph fills a 24px box.

Usage:  python3 tools/build-icons.py
Add an icon: export it from Figma as SVG into assets/icons/figma/<name>.svg, then re-run.
"""
import os, re, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'icons', 'figma')
OUT = os.path.join(ROOT, 'js', 'icons.js')

# Wrapper exports whose glyph sits inside a bigger frame: crop the viewBox (no geometry change)
VIEWBOX = {
    'back': '4 12 24 24',          # 40x48 "leading / Chevron" → chevron centred in 24x24
    'close-circle': '0 12 24 24',  # 40x48 "trailing / Close" → 24px circle
}
# Icons that must keep their own colors (multi-color artwork)
KEEP_COLOR = {'search-phone', 'sun-low', 'sun-high', 'radio-on', 'banner-error'}

PAINT = re.compile(r'\b(fill|stroke)="(?!none|url\()([^"]+)"')
OPAC = re.compile(r'\s(fill|stroke)-opacity="[^"]+"')


def recolor(body):
    """Recolor everything outside <mask>…</mask> and <defs>…</defs>."""
    parts = re.split(r'(<mask\b.*?</mask>|<defs>.*?</defs>)', body, flags=re.S)
    out = []
    for p in parts:
        if p.startswith('<mask') or p.startswith('<defs>'):
            out.append(p)
        else:
            p = PAINT.sub(lambda m: f'{m.group(1)}="currentColor"', p)
            out.append(OPAC.sub('', p))
    return ''.join(out)


icons = {}
for fn in sorted(os.listdir(SRC)):
    if not fn.endswith('.svg'):
        continue
    name = fn[:-4]
    if name.startswith('hamroh-'):
        name = name[len('hamroh-'):]
    svg = open(os.path.join(SRC, fn)).read().strip()
    m = re.match(r'<svg\b([^>]*)>(.*)</svg>$', svg, flags=re.S)
    attrs, body = m.group(1), m.group(2)
    w = float(re.search(r'width="([\d.]+)"', attrs).group(1))
    h = float(re.search(r'height="([\d.]+)"', attrs).group(1))
    vb = VIEWBOX.get(name) or re.search(r'viewBox="([^"]+)"', attrs).group(1)
    if name in VIEWBOX:
        w = h = 24
    if name not in KEEP_COLOR:
        body = recolor(body)
    icons[name] = {'w': int(w), 'h': int(h), 'vb': vb, 'b': body}

js = """/* AUTO-GENERATED by tools/build-icons.py — do not edit by hand.
   Source: SVGs exported from Figma (Samo-home + Hamroh) in assets/icons/figma/.
   icon(name, cls, extra) returns inline SVG that takes CSS `color` (currentColor). */
const ICONS = %s;

let __iconSeq = 0;
function icon(name, cls = 'icon', extra = '') {
  const i = ICONS[name];
  if (!i) { console.warn('Unknown icon', name); return ''; }
  // unique mask/gradient ids per instance (several copies of one icon on a page)
  const sfx = '_' + (++__iconSeq);
  const body = i.b.replace(/id="([^"]+)"/g, (m, id) => `id="${id}${sfx}"`).replace(/url\\(#([^)]+)\\)/g, (m, id) => `url(#${id}${sfx})`);
  const size = cls === 'icon' && !/style=/.test(extra) ? ` style="width:${i.w}px;height:${i.h}px"` : '';
  return `<svg class="${cls}"${size} ${extra} viewBox="${i.vb}" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${body}</svg>`;
}
const ICON_NAMES = Object.keys(ICONS);
""" % json.dumps(icons, separators=(',', ':'))

open(OUT, 'w').write(js)
print(f'{len(icons)} icons → {os.path.relpath(OUT, ROOT)} ({len(js)//1024} KB)')
